"""Complete-deal collection: the G6-safe update boundary (Phase 9).

## The problem this exists to fix

A fixed rollout window ends wherever the step budget runs out, which is usually
mid-deal. The Phase 8 recurrent contract handles that edge by forcing a *chunk*
boundary without resetting memory, so the next window's first stored decision
carries the continuing state as a detached ``h0``.

For Phase 8's purpose -- proving replay reconstructs collection at **fixed
weights** -- that is correct, and the epoch-zero identity holds. But serious
training adds a requirement Phase 8 never had to meet. ``project requirements`` G6:

> Live hidden states computed with pre-update weights become stale after an
> optimizer step.
> Do not silently continue an unfinished deal with recurrent state generated by
> old weights.

Detaching stops *gradients* crossing the optimizer step. It does nothing about
*semantics*: after the step, a carried ``h`` is still the summary a network that
no longer exists would have produced. Measured on this repository, one ordinary
update moved the GRU weights by 2.7e-4 and the carried actor state diverged from
the same history recomputed under the new weights by **1.1e-2** -- against a
control of 1.5e-7 when the weights were left alone. The epoch-zero deviation in
that same update was 1.2e-7, comfortably inside its gate. Epoch-zero is not a
weaker version of G6; it answers a different question.

## The algorithm

The frozen implementation plan's preferred design, implemented additively:

```text
1. reset every environment and zero every recurrent slot
2. step until the rollout budget is reached, storing normally
3. DRAIN: keep stepping until every environment has completed a scored deal,
   storing only for environments that have not yet finished theirs
4. update PPO on the resulting variable-size batch
5. the next window begins from step 1, so nothing is carried
```

After step 3 no learner sequence is unfinished, so **no hidden state survives an
optimizer step at all**. The guarantee is structural rather than argued: the
state container is zeroed and the environments are re-dealt before any collection
that follows an update.

Two consequences worth stating:

- **Every stored sequence ends with ``done=True``.** The truncation bootstrap is
  never used. That is a cleaner credit-assignment story than the fixed window
  had, not merely an equivalent one.
- **The batch size varies.** Deals differ in length, so an update consumes
  between the budget and the budget plus one deal's worth of steps. That is
  accepted deliberately: truncating an active deal to hit a round number is
  exactly the behaviour G6 forbids.

A passed-out hand is **not** an episode end -- no reward is emitted and play
continues -- so the drain runs on to a scored deal. It is still a recurrent reset
and a chunk boundary, as the frozen contract requires.

## A1 fairness

Both architectures share the same base budget, the same drain rule, the same
environment count, the same seeds, the same opponents, the same PPO
configuration and the same optimizer-update count. The feedforward condition
does not need G6 -- it has no recurrent state -- but it runs under the identical
rule so the comparison is of the history encoder and nothing else.

What is **not** matched is the realised transition count. Once the two policies
diverge they bid for different numbers of actions, throw hands in at different
rates, and sit at different points in a deal when the base budget runs out, so
their drains differ. Those differences are reported, never engineered away:
truncating a deal, force-resetting an environment or granting a condition extra
updates to equalise the numbers would either violate G6 or make the budget a
post-hoc choice.
"""

from __future__ import annotations

import time
from typing import Any

import numpy as np

from tarneeb.buffers.recurrent import RecurrentRolloutBuffer
from tarneeb.buffers.rollout import OPPONENT_DECISION_SEAT, RolloutBuffer
from tarneeb.core.cards import NUM_SEATS
from tarneeb.training.recurrent_batched_rollout import BatchedRecurrentRolloutCollector
from tarneeb.training.recurrent_rollout import RecurrentRolloutMetrics
from tarneeb.training.rollout import RolloutCollector, RolloutMetrics

MAX_DRAIN_STEPS = 220
"""Safety bound on the drain.

One deal needs at most a few dozen decisions, and an all-pass redeal restarts
it. This is a stop that turns a hypothetical non-terminating drain into an
immediate, located failure rather than a hang.
"""


class CompleteDealRecurrentCollector(BatchedRecurrentRolloutCollector):
    """Recurrent collection that never leaves a deal unfinished at an update.

    Inherits the Part A cross-environment batching unchanged; only the window
    boundary changes.
    """

    last_collection_steps: int = 0
    """How many vector steps the previous window took, budget plus drain.

    Recorded on the collector rather than in the frozen metrics dataclass, which
    Phase 9 may not modify.
    """

    def collect(self) -> tuple[RecurrentRolloutBuffer, RecurrentRolloutMetrics]:
        """Collect one G6-safe window and return the buffer and metrics."""
        environment_count = self.environments.num_envs
        # Step 1: nothing may be carried into this window.
        self.environments.reset()
        self.state.reset_all()
        self.redeal_counts = np.zeros(environment_count, dtype=np.int64)
        self.assert_consumption_invariant()

        buffer = RecurrentRolloutBuffer(environment_count, self.chunk_length)
        metrics = RecurrentRolloutMetrics()
        self._active = np.ones(environment_count, dtype=bool)
        self._draining = False

        was_training = self.actor.training
        self.actor.eval()
        self.critic.eval()
        start_time = time.perf_counter()

        step = 0
        while True:
            self._one_step(buffer, metrics)
            step += 1
            if step >= self.rollout_length:
                self._draining = True
            if self._draining and not self._active.any():
                break
            if step > self.rollout_length + MAX_DRAIN_STEPS:  # pragma: no cover
                raise AssertionError(
                    f"the drain did not finish within {MAX_DRAIN_STEPS} steps; "
                    f"{int(self._active.sum())} environments are still active"
                )

        metrics.collection_seconds = time.perf_counter() - start_time
        if metrics.collection_seconds > 0:
            metrics.decisions_per_second = metrics.decision_count / metrics.collection_seconds
        metrics.stored_transition_count = buffer.stored_decision_count
        if metrics.learner_rewards:
            metrics.mean_learner_reward = float(np.mean(metrics.learner_rewards))
        self.last_collection_steps = step

        # Step 5: leave nothing behind for the next window to inherit.
        self.environments.reset()
        self.state.reset_all()
        self.redeal_counts = np.zeros(environment_count, dtype=np.int64)

        if was_training:
            self.actor.train()
            self.critic.train()
        return buffer, metrics

    # --- storing is suppressed once an environment has finished draining ----

    def _store_decision(self, environment_index: int, seat: int, *args: Any, **kwargs: Any) -> None:
        """Store only while this environment still owes a completed deal.

        Once it has finished, its subsequent fresh deal is stepped but not
        recorded: recording it would create exactly the unfinished sequence this
        collector exists to prevent.
        """
        if not bool(self._active[environment_index]):
            return
        super()._store_decision(environment_index, seat, *args, **kwargs)

    def _settle_and_reset(
        self,
        vector_step: Any,
        buffer: RecurrentRolloutBuffer,
        metrics: RecurrentRolloutMetrics,
    ) -> None:
        """Settle as the frozen collector does, then retire finished drainers."""
        terminated = np.asarray(vector_step.terminated, dtype=bool)
        super()._settle_and_reset(vector_step, buffer, metrics)
        if self._draining:
            # A scored deal is the episode end. Only then is the environment done
            # owing us a finished sequence; a passed-out hand is not an episode end.
            self._active[terminated] = False

    # --- the guarantee, checkable from outside -------------------------------

    def no_unfinished_learner_sequence(self, buffer: RecurrentRolloutBuffer) -> bool:
        """Return True when every stored sequence ends at a scored deal."""
        return all(sequence and sequence[-1].done for sequence in buffer.sequences.values())

    def recurrent_state_is_zero(self) -> bool:
        """Return True when no hidden state survives into the next window."""
        for policy_id in self.state.policy_ids:
            if bool(self.state.actor_hidden[policy_id].any()):
                return False
            if bool(self.state.critic_hidden[policy_id].any()):
                return False
        return True


class CompleteDealFeedforwardCollector(RolloutCollector):
    """The matched feedforward condition, on the identical update schedule.

    A feedforward policy carries no state, so G6 does not apply to it. It runs
    under the same rule anyway: if the two conditions used different update
    boundaries, A1 would be comparing schedules as much as architectures.

    The frozen rectangular buffer is allocated with drain headroom and filled
    partially; the frozen ``step_cursor`` already means "how many rows are real",
    so this needs no change to ``flat_v1``. Rows belonging to an environment that
    has finished draining are stamped with the frozen opponent sentinel, which
    the frozen buffer already excludes from reward attribution, from the
    advantage recursion and from the training batch.
    """

    last_collection_steps: int = 0
    """How many vector steps the previous window took, budget plus drain."""

    def collect(self) -> tuple[RolloutBuffer, RolloutMetrics]:
        environment_count = self.environments.num_envs
        self.environments.reset()
        self.redeal_counts = np.zeros(environment_count, dtype=np.int64)

        buffer = RolloutBuffer(self.rollout_length + MAX_DRAIN_STEPS, environment_count)
        metrics = RolloutMetrics()
        active = np.ones(environment_count, dtype=bool)
        draining = False
        contract_results: list[float] = []
        absolute_score_differences: list[float] = []
        learner_rewards: list[float] = []

        was_training = self.actor.training
        self.actor.eval()
        self.critic.eval()
        start_time = time.perf_counter()

        step = 0
        while True:
            vector_step = self._collect_one_step(
                buffer,
                metrics,
                active,
                learner_rewards,
                contract_results,
                absolute_score_differences,
            )
            step += 1
            if step >= self.rollout_length:
                draining = True
            if draining:
                active[np.asarray(vector_step.terminated, dtype=bool)] = False
            if draining and not active.any():
                break
            if step > self.rollout_length + MAX_DRAIN_STEPS:  # pragma: no cover
                raise AssertionError("the feedforward drain did not finish in time")

        metrics.collection_seconds = time.perf_counter() - start_time
        if metrics.collection_seconds > 0:
            metrics.decisions_per_second = metrics.decision_count / metrics.collection_seconds
        metrics.mean_bid = float(np.mean(metrics.winning_bids)) if metrics.winning_bids else None
        metrics.contract_success_rate = (
            float(np.mean(contract_results)) if contract_results else None
        )
        metrics.mean_absolute_score_difference = (
            float(np.mean(absolute_score_differences)) if absolute_score_differences else None
        )
        metrics.mean_learner_reward = float(np.mean(learner_rewards)) if learner_rewards else None
        self.last_collection_steps = step

        self.environments.reset()
        self.redeal_counts = np.zeros(environment_count, dtype=np.int64)

        if was_training:
            self.actor.train()
            self.critic.train()
        return buffer, metrics

    def _collect_one_step(
        self,
        buffer: RolloutBuffer,
        metrics: RolloutMetrics,
        active: np.ndarray,
        learner_rewards: list[float],
        contract_results: list[float],
        absolute_score_differences: list[float],
    ) -> Any:
        """One vector step, mirroring the frozen collector's body.

        Duplicated rather than shared because sharing would require editing the
        frozen method. The equivalence test in
        ``tests/test_complete_deal_rollout.py`` is what keeps the two aligned.
        """
        import torch

        from tarneeb.core.actions import NO_TRUMP_ACTION, PASS_ACTION
        from tarneeb.models.masking import MaskedCategorical, actions_are_legal

        environment_count = self.environments.num_envs
        acting_seats = self.environments.acting_seats()
        learner_flags = self.learner_decision_flags(acting_seats)
        learner_indices = np.flatnonzero(learner_flags)
        opponent_indices = np.flatnonzero(~learner_flags)

        observations, history_ids, history_masks, legal_action_masks = self._gather_learner_inputs(
            learner_indices
        )
        observation_tensor = torch.from_numpy(observations)
        history_id_tensor = torch.from_numpy(history_ids.astype(np.int64))
        history_mask_tensor = torch.from_numpy(history_masks)
        legal_mask_tensor = torch.from_numpy(legal_action_masks)

        with torch.no_grad():
            logits = self.actor(observation_tensor, history_id_tensor, history_mask_tensor)
            distribution = MaskedCategorical.from_logits(logits, legal_mask_tensor)
            selected_actions = distribution.sample(self.action_sampling_generator)
            action_log_probabilities = distribution.log_probability_of(selected_actions)
            state_values = self.critic(observation_tensor, history_id_tensor, history_mask_tensor)

        if not actions_are_legal(selected_actions, legal_mask_tensor):
            metrics.illegal_action_count += int(learner_indices.size)
            raise AssertionError("the policy sampled an action its legal mask forbids")
        no_trump_selections = int((selected_actions == NO_TRUMP_ACTION).sum())
        if no_trump_selections:
            metrics.no_trump_action_count += no_trump_selections
            raise AssertionError("the policy selected the reserved no-trump action 64")

        learner_actions = selected_actions.numpy()
        opponent_actions = self._opponent_actions(opponent_indices)

        step_actions = np.zeros(environment_count, dtype=np.int64)
        step_actions[learner_indices] = learner_actions
        for environment_index, action in opponent_actions.items():
            step_actions[environment_index] = action

        learner_in_auction = legal_action_masks[:, PASS_ACTION]
        metrics.auction_decision_count += int(learner_in_auction.sum())
        metrics.pass_action_count += int(
            np.count_nonzero(learner_actions[learner_in_auction] == PASS_ACTION)
        )

        vector_step = self.environments.step(step_actions)

        # A retired environment's decisions are stamped with the frozen opponent
        # sentinel, so nothing it did after finishing can reach a gradient.
        stored_seats = np.where(learner_flags & active, acting_seats, OPPONENT_DECISION_SEAT)
        buffer.store_step(
            acting_seats=stored_seats,
            **self._scatter_to_all_environments(
                learner_indices,
                environment_count,
                observations=observations,
                history_ids=history_ids,
                history_masks=history_masks,
                legal_action_masks=legal_action_masks,
                selected_actions=learner_actions,
                action_log_probabilities=action_log_probabilities.numpy(),
                state_values=state_values.numpy(),
            ),
        )

        metrics.environment_steps += environment_count
        metrics.decision_count += environment_count
        metrics.learner_decision_count += int((stored_seats != OPPONENT_DECISION_SEAT).sum())

        for terminated_index in np.flatnonzero(vector_step.terminated):
            environment_index = int(terminated_index)
            rewards_by_seat = vector_step.rewards_by_seat[environment_index]
            _seats_paid, reward_paid = buffer.settle_completed_deal(
                environment_index, rewards_by_seat
            )
            metrics.total_reward_paid += reward_paid
            metrics.total_reward_emitted += float(rewards_by_seat.sum())
            metrics.completed_deals += 1
            learner_team = int(self.learner_teams[environment_index])
            learner_rewards.append(float(rewards_by_seat[learner_team]))
            self._record_deal_statistics(
                environment_index,
                learner_team,
                metrics,
                contract_results,
                absolute_score_differences,
            )
            self.opponents[environment_index].reset()

        metrics.passed_out_deals += self._count_new_redeals()

        if vector_step.terminated.any():
            self.environments.reset_terminated(vector_step.terminated)
            self.redeal_counts[vector_step.terminated] = 0

        return vector_step


def no_unfinished_flat_sequence(buffer: RolloutBuffer) -> bool:
    """Return True when every learner seat's last stored row ends a deal."""
    rows = buffer.acting_seats[: buffer.step_cursor]
    for environment_index in range(buffer.environment_count):
        for seat in range(NUM_SEATS):
            positions = np.flatnonzero(rows[:, environment_index] == seat)
            if positions.size == 0:
                continue
            if not bool(buffer.is_last_decision_of_deal[positions[-1], environment_index]):
                return False
    return True
